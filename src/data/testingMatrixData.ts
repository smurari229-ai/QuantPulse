export function getTestMatrixSummary(cases: TestCaseItem[] = INITIAL_TEST_CASES): TestMatrixSummary {
  const total = cases.length;
  const passed = cases.filter((c) => c.status === 'PASS').length;
  const failed = cases.filter((c) => c.status === 'FAIL').length;
  const blocked = cases.filter((c) => c.status === 'BLOCKED').length;
  const notRun = cases.filter((c) => c.status === 'NOT_RUN').length;
  const passPercentage = total > 0 ? Math.round((passed / total) * 1000) / 10 : 0;

  return {
    total,
    passed,
    failed,
    blocked,
    notRun,
    passPercentage,
  };
}
